# Task 5: Difference between Bag of Words and TF-IDF


print("Difference between Bag of Words and TF-IDF")
print("-------------------------------------------")

print("\n1. Bag of Words:")
print("Bag of Words represents text using word counts.")
print("It gives importance based on how many times a word appears.")

print("\n2. TF-IDF:")
print("TF-IDF represents text using weighted word values.")
print("It gives more importance to important and less common words.")

print("\nReal-World Example:")
print("TF-IDF can be useful in a shopping app like Flipkart")
print("for finding products related to a user's search.")
print("It can give more importance to specific words such as")
print("'wireless', 'gaming', or 'waterproof' instead of common words.")